import { cleanup, fireEvent, render, screen, within } from "@testing-library/react";
import { QueryClient, QueryClientProvider } from "@tanstack/react-query";
import { afterEach, describe, expect, it, vi } from "vitest";
import type { ReactNode } from "react";
vi.mock("@tanstack/react-router", () => ({ createFileRoute: () => (options: unknown) => ({ options }) }));
vi.mock("@tanstack/react-start", () => ({ useServerFn: (fn: unknown) => fn }));
vi.mock("@/components/SiteLayout", () => ({ SiteLayout: ({ children }: { children: ReactNode }) => <main>{children}</main>, useSiteSession: () => ({ data: { user: null } }) }));
vi.mock("@/integrations/supabase/client", () => ({ supabase: {} }));
vi.mock("@/lib/support-chat.functions", () => ({ askSupportChat: vi.fn() }));
import { Route } from "@/routes/roles";
import { SupportChatWidget } from "@/components/SupportChatWidget";
afterEach(cleanup);
describe("Career guidance and chat placement", () => {
  it("shows suitability guidance only when a career is expanded", () => {
    const client = new QueryClient({ defaultOptions: { queries: { staleTime: Infinity, retry: false } } });
    client.setQueryData(["public-career-content"], [{ name: "Accountant", description: "Saved admin description", school_skills: ["Custom school skill"], workplace_skills: ["Custom workplace skill"] }]);
    client.setQueryData(["placements"], []); client.setQueryData(["no-availability-message"], null);
    const Page = Route.options.component as () => React.JSX.Element;
    render(<QueryClientProvider client={client}><Page /></QueryClientProvider>);
    expect(screen.queryByText("Ideal For")).not.toBeInTheDocument();
    expect(screen.queryByRole("dialog")).not.toBeInTheDocument();
    const business = screen.getByRole("button", { name: "Business & Finance" });
    expect(business).toHaveAttribute("aria-expanded", "false");
    fireEvent.click(business);
    fireEvent.click(screen.getByText(/Accounting & Audit/).closest("button")!);
    fireEvent.click(screen.getByText("Accountant").closest("button")!);
    const dialog = screen.getByRole("dialog");
    expect(within(dialog).getByText("Ideal For")).toBeVisible();
    expect(within(dialog).getByText("Saved admin description")).toBeVisible();
    expect(within(dialog).getByText("Custom school skill")).toBeVisible();
    expect(within(dialog).getByText("Custom workplace skill")).toBeVisible();
    expect(within(dialog).queryByText("Financial reporting")).not.toBeInTheDocument();
    expect(within(dialog).getByText(/People who enjoy numbers, organised records/)).toBeVisible();
    fireEvent.click(within(dialog).getByRole("button", { name: "Close" }));
    expect(screen.queryByText("Ideal For")).not.toBeInTheDocument();
    client.clear();
  });
  it("places Reddy inside the chat dialog beside the opening message", () => {
    render(<SupportChatWidget />);
    fireEvent.click(screen.getByRole("button", { name: "Open support chat" }));
    const chat = screen.getByRole("dialog", { name: "Ask Job Shadow" });
    expect(within(chat).getByRole("img", { name: "Reddy" })).toBeVisible();
    expect(within(chat).getByText(/Hi, I'm Reddy/)).toBeVisible();
    fireEvent.click(within(chat).getByRole("button", { name: "Close support chat" }));
    expect(screen.queryByRole("dialog")).not.toBeInTheDocument();
  });
});
